class TestOutputGate:
    """PostProcessNode refuses to release credential-like content.

    Drives PostProcessNode directly, since it owns the output boundary. An
    injected secret in state["result"] must yield an error status and a fixed
    notice for BOTH formatted_output and result — the raw secret must never
    survive into the surfaced output.
    """

    def test_api_key_in_result_is_blocked(self):
        report_with_key = "# Administrative Report\n\n## Notes\n" f"<!-- debug: api_key={_SIMULATED_API_KEY} -->\n"
        result = PostProcessNode().execute({"result": report_with_key})
        assert result.get("status") == AgentStatus.ERROR.value, (
            f"Expected the output to be blocked, got {result.get('status')}. "
            f"formatted_output snippet: {str(result.get('formatted_output',''))[:80]!r}"
        )

    def test_api_key_not_in_output_after_block(self):
        report_with_key = "# Administrative Report\n\n## Notes\n" f"<!-- debug: api_key={_SIMULATED_API_KEY} -->\n"
        result = PostProcessNode().execute({"result": report_with_key})
        # Gate BOTH surfaced fields.
        assert _SIMULATED_API_KEY not in result.get(
            "formatted_output", ""
        ), "Simulated API key leaked into formatted_output"
        assert _SIMULATED_API_KEY not in result.get("result", ""), "Simulated API key leaked into result"

    def test_blocked_output_is_sanitised_stub(self):
        report_with_key = "# Administrative Report\n\n## Notes\n" f"<!-- debug: api_key={_SIMULATED_API_KEY} -->\n"
        result = PostProcessNode().execute({"result": report_with_key})
        # Both surfaced fields carry the sanitised stub marker.
        for field in ("formatted_output", "result"):
            output = result.get(field, "")
            assert "blocked" in output.lower(), f"Expected the fixed blocked notice in {field}, got: {output[:200]!r}"
        assert result.get("error_log"), "Blocked output must carry an error_log entry"

    def test_credential_assignment_in_result_is_blocked(self):
        report_with_cred = "# Administrative Report\n\n## Config\n" f"Internal note: {_SIMULATED_CRED_STR}\n"
        result = PostProcessNode().execute({"result": report_with_cred})
        assert (
            result.get("status") == AgentStatus.ERROR.value
        ), f"A credential assignment must be blocked, got {result.get('status')}"
        assert _SIMULATED_CRED_STR not in result.get("formatted_output", "")
        assert _SIMULATED_CRED_STR not in result.get("result", "")

    def test_jwt_in_result_is_blocked(self):
        report_with_jwt = "# Administrative Report\n\n## Notes\n" f"Token observed: {_SIMULATED_JWT}\n"
        result = PostProcessNode().execute({"result": report_with_jwt})
        assert (
            result.get("status") == AgentStatus.ERROR.value
        ), f"A token pattern must be blocked, got {result.get('status')}"

    def test_bearer_token_in_result_is_blocked(self):
        report_with_bearer = "# Administrative Report\n\n## Notes\n" f"Authorization: {_SIMULATED_BEARER}\n"
        result = PostProcessNode().execute({"result": report_with_bearer})
        assert (
            result.get("status") == AgentStatus.ERROR.value
        ), f"A bearer token must be blocked, got {result.get('status')}"

    def test_clean_report_passes_s3_gate(self):
        """A clean report must NOT trip the gate (success, unchanged)."""
        result = PostProcessNode().execute({"result": _CLEAN_REPORT})
        assert result.get("status") == AgentStatus.SUCCESS.value, (
            f"A clean report must pass the output gate, got {result.get('status')}. "
            f"error_log: {result.get('error_log')}"
        )
        assert (
            result.get("formatted_output") == _CLEAN_REPORT
        ), "Clean report must pass through formatted_output unchanged"
