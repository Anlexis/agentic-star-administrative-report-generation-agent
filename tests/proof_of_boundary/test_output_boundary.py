# PB — Output boundary: nothing personal and nothing credential-shaped is
# released. The template's stated invariant, in both directions:
#
#  (1) Inbound (TestNoPersonalDataInReport): personal-data shapes are
#      rewritten out of caller text at the request boundary, so the report is
#      synthesized only from already-stripped material and an injected
#      identification number, e-mail or telephone number cannot surface in
#      the rendered report. Proven end to end through a real invocation.
#
#  (2) Outbound (TestOutputGate): PostProcessNode refuses to release content
#      matching a credential shape or a personal-data shape, clearing every
#      output-bearing field as it blocks — the framework's own envelope falls
#      back to the ungated report otherwise.
#
# Deterministic — no model, no network. framework.* / src.* imports only.

import json


from framework.schemas.agent_status import AgentStatus
from framework.schemas.invocation_context import InvocationContext

from src.graph.graph import Graph
from src.nodes.post_process_node import PostProcessNode


# Simulated resident-PII tokens — NOT real data.
_MY_NUMBER = "1234-5678-9012"
_EMAIL = "resident.taro@example.com"
_PHONE = "03-9876-5432"

# Payload with resident PII embedded both in free-text and in PII-named fields.
_PAYLOAD_WITH_PII = json.dumps(
    {
        "report_type": "incident",
        "subject": "Resident complaint follow-up",
        "period": "2025-05",
        "department": "Citizen Affairs",
        "fields": {
            "applicant_name": "Yamada Hanako",
            "address": "1-2-3 Chiyoda, Tokyo",
            "background": f"Filed by resident, My Number {_MY_NUMBER}, contact {_EMAIL}.",
            "findings": f"Callback attempted to {_PHONE}; unresolved.",
        },
        "data_points": [{"case_age_days": 14}],
    },
    ensure_ascii=False,
)


def _run(user_input: str) -> dict:
    # Fully-trusted internal context — the backbone trust gate denies ANONYMOUS.
    ctx = InvocationContext.for_internal(caller_id="test-suite")
    return Graph().invoke(user_input, ctx=ctx)


class TestNoPersonalDataInReport:
    """The rendered report carries no injected personal-data token."""

    def test_run_succeeds(self):
        result = _run(_PAYLOAD_WITH_PII)
        assert (
            result.get("status") == AgentStatus.SUCCESS.value
        ), f"Expected success, got {result.get('status')}. result={result!r}"

    def test_my_number_not_in_report(self):
        report = _run(_PAYLOAD_WITH_PII).get("output", "")
        assert _MY_NUMBER not in report, "My Number token leaked into the report"

    def test_email_not_in_report(self):
        report = _run(_PAYLOAD_WITH_PII).get("output", "")
        assert _EMAIL not in report, "Resident e-mail leaked into the report"

    def test_phone_not_in_report(self):
        report = _run(_PAYLOAD_WITH_PII).get("output", "")
        assert _PHONE not in report, "Resident phone number leaked into the report"

    def test_pii_field_values_redacted_in_report(self):
        """applicant_name / address are PII-keyed → redacted, never rendered raw."""
        report = _run(_PAYLOAD_WITH_PII).get("output", "")
        assert "Yamada Hanako" not in report, "Resident name leaked into the report"
        assert "1-2-3 Chiyoda, Tokyo" not in report, "Resident address leaked into the report"

    def test_report_still_non_empty(self):
        """Stripping PII must not blank the report — the structure survives."""
        report = _run(_PAYLOAD_WITH_PII).get("output", "")
        assert report.strip()
        # The redaction marker is the visible evidence the strip ran.
        assert "[REDACTED]" in report


